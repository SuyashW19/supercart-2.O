export async function autoSeedSupabase(supabaseClient: any): Promise<{
  success: boolean;
  message: string;
  count: number;
}> {
  try {
    // 1. Seed Categories
    const categoriesPayload = DEFAULT_SEED_CATEGORIES.map((c, i) => ({
      id: c.id,
      name: c.name,
      name_hi: c.name_hi || null,
      icon_name: c.iconName || c.icon_name || "ShoppingBag",
      color: c.color || null,
      sort_order: i + 1,
      is_active: true,
    }));
    const { error: catErr } = await supabaseClient
      .from("categories")
      .upsert(categoriesPayload, { onConflict: "id" });
    if (catErr) {
      return { success: false, message: `Categories insert failed: ${catErr.message}`, count: 0 };
    }

    // 2. Seed Subcategories
    const subcatsPayload: any[] = [];
    DEFAULT_SEED_CATEGORIES.forEach((cat) => {
      cat.subcategories.forEach((sub, idx) => {
        subcatsPayload.push({
          category_id: cat.id,
          name: sub,
          sort_order: idx + 1,
        });
      });
    });
    // Upsert subcategories
    await supabaseClient.from("subcategories").upsert(subcatsPayload, { onConflict: "category_id,name" }).then();

    // 3. Seed Banners
    const bannersPayload = DEFAULT_SEED_BANNERS.map((b) => ({
      id: b.id,
      title: b.title,
      subtitle: b.subtitle,
      image_url: b.image_url,
      cta_text: b.cta_text,
      category_id: b.category_id,
      sort_order: b.sort_order,
      is_active: true,
    }));
    await supabaseClient.from("banners").upsert(bannersPayload, { onConflict: "id" }).then();

    // 4. Seed Products in batches of 40 to avoid payload limits
    const productsPayload = DEFAULT_SEED_PRODUCTS.map((p) => ({
      id: p.id,
      name: p.name,
      name_hi: p.name_hi || null,
      brand: p.brand,
      category_id: p.category,
      subcategory: p.subcategory,
      price: p.price,
      mrp: p.mrp,
      weight: p.weight,
      discount_pct: p.discount_pct,
      image_url: p.image_url,
      stock: p.stock,
      rating: p.rating,
      reviews_count: p.reviews_count,
      eta_minutes: p.eta_minutes || 10,
      is_active: true,
      description: p.description,
      nutrition: p.nutrition || {},
      shelf_life: p.shelf_life || "Fresh",
      tags: p.tags || [],
    }));

    const BATCH_SIZE = 35;
    for (let i = 0; i < productsPayload.length; i += BATCH_SIZE) {
      let batch: any[] = productsPayload.slice(i, i + BATCH_SIZE);
      let { error: prodErr } = await supabaseClient
        .from("products")
        .upsert(batch, { onConflict: "id" });

      if (prodErr && prodErr.code === "42703") {
        // If column doesn't exist on remote table, strip columns not yet migrated
        const match = prodErr.message.match(/column "?([a-zA-Z0-9_]+)"? does not exist/);
        const missing = match ? match[1] : null;
        batch = batch.map((item) => {
          const copy = { ...item };
          if (missing) delete copy[missing];
          else {
            delete copy.is_active;
            delete copy.nutrition;
            delete copy.eta_minutes;
          }
          return copy;
        });
        const retry = await supabaseClient
          .from("products")
          .upsert(batch, { onConflict: "id" });
        prodErr = retry.error;
      }

      if (prodErr) {
        return {
          success: false,
          message: `Products batch ${i / BATCH_SIZE + 1} failed: ${prodErr.message}`,
          count: i,
        };
      }
    }

    return {
      success: true,
      message: `Successfully seeded ${productsPayload.length} products, 13 categories, and banners into Supabase!`,
      count: productsPayload.length,
    };
  } catch (err: any) {
    return {
      success: false,
      message: err?.message || "Unknown error seeding database",
      count: 0,
    };
  }
}

